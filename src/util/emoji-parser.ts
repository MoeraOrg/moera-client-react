import twemojiData from "util/twemoji-data.json";
import { twemojiUrl } from "util/twemoji";

export interface EmojiEntity {
    text: string;
    url: string;
    indices: [number, number];
}

// Match the entire sequence before looking it up, including sequences newer than our image set.
// U+E50A is a legacy private-use character present in the Twemoji catalog.
const EMOJI_ELEMENT = "(?:\\p{Regional_Indicator}{2}|[\\p{Emoji}\\p{Extended_Pictographic}\\ue50a])"
    + "[\\ufe0e\\ufe0f\\p{Emoji_Modifier}\\u20e3\\u{e0020}-\\u{e007f}]*";
const EMOJI_PATTERN = new RegExp(EMOJI_ELEMENT + "(?:\\u200d" + EMOJI_ELEMENT + ")*", "gu");

// The catalog is generated by scripts/update-twemoji.js from the SVGs on our CDN.
// Match normalized filenames, then restore presentation selectors required by the real SVG names.
const SUPPORTED_EMOJI_PATTERN = new RegExp(twemojiData.pattern);
const SELECTOR_BASES = new Set(twemojiData.selectorBases);
const EMOJI_EXCEPTIONS: Record<string, string> = twemojiData.exceptions;

export function parseEmojis(text: string): EmojiEntity[] {
    const entities: EmojiEntity[] = [];
    for (const match of text.matchAll(EMOJI_PATTERN)) {
        const emoji = match[0];
        // Copyright and trademark signs are text unless an emoji presentation selector is present.
        if (emoji === "©" || emoji === "®" || emoji === "™") {
            continue;
        }
        const parts = Array.from(emoji)
            .filter(char => char !== "\ufe0f")
            .map(char => char.codePointAt(0)!.toString(16));
        const key = parts.join("-");
        if (!SUPPORTED_EMOJI_PATTERN.test(key)) {
            continue;
        }
        const code = EMOJI_EXCEPTIONS[key] ?? (parts.includes("200d")
            ? parts.map((part, index) => SELECTOR_BASES.has(part) && !/^1f3f[b-f]$/.test(parts[index + 1] ?? "")
                ? `${part}-fe0f` : part).join("-")
            : key);
        entities.push({text: emoji, url: twemojiUrl(code), indices: [match.index, match.index + emoji.length]});
    }
    return entities;
}
